import React, { useState, useEffect } from 'react';
import { api } from '../api/client';
import { Sliders, Play, Square, RotateCcw, Sparkles, AlertTriangle, Terminal } from 'lucide-react';

const SCENARIOS = [
  {
    id: 'baseline',
    name: 'Stable Baseline Operation',
    desc: 'Equilibrium with low Gaussian noise (< 0.05 mm), diurnal temperature cycle, nominal vibration.',
  },
  {
    id: 'gradual_settlement',
    name: 'Gradual Settlement (Consolidation)',
    desc: 'Steady constant-velocity subsidence (~2 mm / 10 steps), simulating secondary soil consolidation.',
  },
  {
    id: 'accelerating_subsidence',
    name: 'Accelerating Subsidence (Tertiary Creep)',
    desc: 'Exponential displacement with positive acceleration (a > 0.5 mm/hr²), triggering WARNING and CRITICAL alerts.',
  },
  {
    id: 'sudden_collapse',
    name: 'Sudden Fault Slip / Crown-Hole Sinkhole',
    desc: 'Abrupt step displacement (> 35 mm) with severe seismic vibration impact at t=10.',
  },
  {
    id: 'vibration_blast',
    name: 'Controlled Blasting Vibration Event',
    desc: 'High transient vibration spikes (12 - 24 m/s²) without permanent vertical ground settlement.',
  },
  {
    id: 'sensor_drift',
    name: 'Transducer Sensor Drift',
    desc: 'Electronic calibration drift on tilt channels without physical displacement, testing false alarm rejection.',
  },
  {
    id: 'packet_loss',
    name: 'Edge Packet Loss & Delay',
    desc: 'Simulates dropped packets and gateway buffering, testing idempotent backfill & replay.',
  },
];

export function SimulatorPage({ latestTelemetry }) {
  const [status, setStatus] = useState(null);
  const [scenario, setScenario] = useState('accelerating_subsidence');
  const [intervalSec, setIntervalSec] = useState(2.0);
  const [nodeCount, setNodeCount] = useState(6);
  const [seed, setSeed] = useState(42);
  const [telemetryLog, setTelemetryLog] = useState([]);
  const [loading, setLoading] = useState(false);

  useEffect(() => {
    loadStatus();
    const interval = setInterval(loadStatus, 4000);
    return () => clearInterval(interval);
  }, []);

  useEffect(() => {
    if (latestTelemetry && latestTelemetry.data_source === 'simulator') {
      setTelemetryLog((prev) => [latestTelemetry, ...prev.slice(0, 19)]);
    }
  }, [latestTelemetry]);

  const loadStatus = async () => {
    try {
      const data = await api.getSimulatorStatus();
      setStatus(data);
      if (data.scenario) setScenario(data.scenario);
      if (data.interval_sec) setIntervalSec(data.interval_sec);
    } catch (e) {
      console.error(e);
    }
  };

  const handleStart = async () => {
    setLoading(true);
    try {
      const res = await api.startSimulator({
        scenario,
        interval_sec: parseFloat(intervalSec),
        node_count: parseInt(nodeCount, 10),
        seed: parseInt(seed, 10),
      });
      setStatus(res);
    } catch (err) {
      alert(`Start error: ${err.message}`);
    } finally {
      setLoading(false);
    }
  };

  const handleStop = async () => {
    setLoading(true);
    try {
      const res = await api.stopSimulator();
      setStatus(res);
    } catch (err) {
      alert(`Stop error: ${err.message}`);
    } finally {
      setLoading(false);
    }
  };

  const handleReset = async () => {
    try {
      const res = await api.resetSimulator();
      setStatus(res);
      setTelemetryLog([]);
    } catch (err) {
      alert(`Reset error: ${err.message}`);
    }
  };

  return (
    <div className="page-wrapper" style={{ display: 'flex', flexDirection: 'column', gap: '1.25rem' }}>
      {/* Prominent Simulated Data Warning Banner */}
      <div style={{
        backgroundColor: 'rgba(234, 179, 8, 0.1)',
        border: '1px solid #ca8a04',
        borderRadius: '8px',
        padding: '0.85rem 1.25rem',
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'space-between',
        flexWrap: 'wrap',
        gap: '0.75rem'
      }}>
        <div style={{ display: 'flex', alignItems: 'center', gap: '0.75rem' }}>
          <Sparkles size={20} style={{ color: '#facc15' }} />
          <div>
            <strong style={{ color: '#facc15', fontSize: '0.9rem' }}>DETERMINISTIC SENSOR SIMULATOR ACTIVE</strong>
            <p style={{ fontSize: '0.75rem', color: '#cbd5e1', marginTop: '0.1rem' }}>
              All records generated by this engine are synthetic and explicitly tagged as simulated. They demonstrate algorithmic response and do NOT reflect real mine measurements.
            </p>
          </div>
        </div>

        <div style={{ display: 'flex', gap: '0.5rem' }}>
          <span className="badge badge-warning">
            {status?.is_running ? 'Simulation Clock Running' : 'Simulation Engine Idle'}
          </span>
        </div>
      </div>

      {/* Simulator Control Grid */}
      <div style={{ display: 'grid', gridTemplateColumns: '1.2fr 1fr', gap: '1.25rem' }}>
        {/* Scenario Selection & Controls */}
        <div className="card" style={{ display: 'flex', flexDirection: 'column', gap: '1rem' }}>
          <h2 style={{ fontSize: '1rem', fontWeight: 600, color: '#f8fafc' }}>
            Geotechnical Test Scenario
          </h2>

          <div style={{ display: 'flex', flexDirection: 'column', gap: '0.6rem' }}>
            {SCENARIOS.map((s) => (
              <label
                key={s.id}
                style={{
                  display: 'flex',
                  alignItems: 'flex-start',
                  gap: '0.75rem',
                  padding: '0.75rem',
                  borderRadius: '6px',
                  backgroundColor: scenario === s.id ? 'rgba(56, 189, 248, 0.1)' : '#1e293b',
                  border: scenario === s.id ? '1px solid #38bdf8' : '1px solid transparent',
                  cursor: 'pointer',
                  transition: 'all 0.15s ease'
                }}
              >
                <input
                  type="radio"
                  name="scenario"
                  value={s.id}
                  checked={scenario === s.id}
                  onChange={(e) => setScenario(e.target.value)}
                  style={{ marginTop: '0.2rem' }}
                />
                <div>
                  <div style={{ fontWeight: 600, fontSize: '0.85rem', color: scenario === s.id ? '#38bdf8' : '#f8fafc' }}>
                    {s.name}
                  </div>
                  <div style={{ fontSize: '0.75rem', color: '#94a3b8', marginTop: '0.15rem' }}>
                    {s.desc}
                  </div>
                </div>
              </label>
            ))}
          </div>

          <div style={{ display: 'grid', gridTemplateColumns: 'repeat(3, 1fr)', gap: '0.75rem', marginTop: '0.5rem' }}>
            <div>
              <label style={{ display: 'block', fontSize: '0.75rem', color: '#94a3b8', marginBottom: '0.2rem' }}>
                Interval (sec)
              </label>
              <input
                type="number"
                step="0.5"
                min="0.5"
                max="60"
                value={intervalSec}
                onChange={(e) => setIntervalSec(e.target.value)}
                style={{ width: '100%', padding: '0.4rem', backgroundColor: '#1e293b', border: '1px solid #334155', borderRadius: '4px', color: '#ffffff' }}
              />
            </div>
            <div>
              <label style={{ display: 'block', fontSize: '0.75rem', color: '#94a3b8', marginBottom: '0.2rem' }}>
                Node Count (1-6)
              </label>
              <input
                type="number"
                min="1"
                max="6"
                value={nodeCount}
                onChange={(e) => setNodeCount(e.target.value)}
                style={{ width: '100%', padding: '0.4rem', backgroundColor: '#1e293b', border: '1px solid #334155', borderRadius: '4px', color: '#ffffff' }}
              />
            </div>
            <div>
              <label style={{ display: 'block', fontSize: '0.75rem', color: '#94a3b8', marginBottom: '0.2rem' }}>
                Random Seed
              </label>
              <input
                type="number"
                value={seed}
                onChange={(e) => setSeed(e.target.value)}
                style={{ width: '100%', padding: '0.4rem', backgroundColor: '#1e293b', border: '1px solid #334155', borderRadius: '4px', color: '#ffffff' }}
              />
            </div>
          </div>

          <div style={{ display: 'flex', gap: '0.75rem', marginTop: '0.75rem' }}>
            {!status?.is_running ? (
              <button
                onClick={handleStart}
                disabled={loading}
                className="btn btn-primary"
                style={{ flex: 1 }}
              >
                <Play size={15} /> Start Scenario
              </button>
            ) : (
              <button
                onClick={handleStop}
                disabled={loading}
                className="btn btn-danger"
                style={{ flex: 1 }}
              >
                <Square size={15} /> Halt Simulation
              </button>
            )}

            <button onClick={handleReset} className="btn btn-secondary" title="Reset scenario state">
              <RotateCcw size={15} /> Reset
            </button>
          </div>
        </div>

        {/* Live Terminal Output Feed */}
        <div className="card" style={{ display: 'flex', flexDirection: 'column', backgroundColor: '#070b14', border: '1px solid #1e293b' }}>
          <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', borderBottom: '1px solid #1e293b', paddingBottom: '0.5rem', marginBottom: '0.5rem' }}>
            <div style={{ display: 'flex', alignItems: 'center', gap: '0.4rem', fontSize: '0.8rem', color: '#38bdf8', fontWeight: 600 }}>
              <Terminal size={14} />
              <span>LIVE SYNTHETIC EMISSION FEED</span>
            </div>
            <span style={{ fontSize: '0.7rem', color: '#64748b' }}>
              Ticks: {status?.ticks_generated || 0}
            </span>
          </div>

          <div style={{ flex: 1, overflowY: 'auto', maxHeight: '420px', display: 'flex', flexDirection: 'column', gap: '0.35rem', fontFamily: 'monospace', fontSize: '0.75rem' }}>
            {telemetryLog.length === 0 ? (
              <div style={{ color: '#475569', fontStyle: 'italic', padding: '1rem' }}>
                Waiting for simulation ticks... Click "Start Scenario" to generate synthetic telemetry.
              </div>
            ) : (
              telemetryLog.map((t, idx) => (
                <div key={t.event_id || idx} style={{ borderBottom: '1px solid #111827', paddingBottom: '0.25rem', color: '#cbd5e1' }}>
                  <span style={{ color: '#64748b' }}>[{new Date(t.timestamp).toLocaleTimeString()}]</span>{' '}
                  <strong style={{ color: '#38bdf8' }}>{t.node_id}</strong>:{' '}
                  <span style={{ color: t.displacement_mm > 15 ? '#f87171' : '#a7f3d0' }}>
                    d={t.displacement_mm !== null ? `${t.displacement_mm.toFixed(2)}mm` : 'N/A'}
                  </span>{' '}
                  <span style={{ color: '#cbd5e1' }}>
                    v={t.velocity_mm_hr !== null ? `${t.velocity_mm_hr.toFixed(2)}mm/h` : '-'}
                  </span>{' '}
                  <span style={{ color: '#e2e8f0' }}>
                    tilt={t.vector_tilt_deg !== null ? `${t.vector_tilt_deg.toFixed(1)}°` : '-'}
                  </span>{' '}
                  <span style={{ color: '#94a3b8' }}>
                    vib={t.vibration_rms_ms2 !== null ? `${t.vibration_rms_ms2.toFixed(1)}m/s²` : '-'}
                  </span>
                </div>
              ))
            )}
          </div>
        </div>
      </div>
    </div>
  );
}
